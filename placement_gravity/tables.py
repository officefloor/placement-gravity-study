"""Tables from a measured chain: hosts, runs, classes, additions and outcomes (PLAN.md §4.2–4.6).

Bindings (the instrument's measure of how far an addition is held to its location):

- ``binding_method``: the host method's pre-existing parameters (not injected) and locals the added
  code uses;
- ``binding_field`` and ``binding_class_method``: the host class's pre-existing fields and methods it uses;
  together the **class bindings**;
Bindings are read from the **logic lines** the change adds or edits (a method's body statements;
signatures, declarations and constructor wiring are organisation). Every reference on those lines
counts, edited lines alike. ``tok_*`` counts only the references an edit itself introduced, as a
secondary reading. Not bindings: class **utilities** (loggers), which any class can declare, and
``birth_binding`` (the values a caller passes a new method: the binding is already on the caller's line).
``unresolved`` lists references that resolve to nothing seen (inherited members, static imports).
"""

from __future__ import annotations

import re
from pathlib import Path

import yaml

from . import flow

#: A host whose added positions are at least this share moved code is a re-placement.
REPLACEMENT_SHARE = 0.5


def stream(checkpoints_yaml: Path, density_md: Path | None = None) -> dict[int, dict]:
    """cp number (1-based, the stream's order) -> {id, type, mutates, rules, crosses}. ``mutates``
    lists the checkpoints whose rules this one changes (both streams). With the ui stream's
    ``acceptance/DENSITY.md``, ``rules`` are the rules this checkpoint introduces and ``crosses`` the
    checkpoints whose rules they interact with (``crossings``); otherwise both are empty."""
    doc = yaml.safe_load(checkpoints_yaml.read_text())
    out = {i: {"id": c["id"], "type": c.get("type", "additive"),
               "mutates": list(c.get("mutates") or []), "rules": [], "crosses": []}
           for i, c in enumerate(doc["checkpoints"], start=1)}
    if density_md is not None:
        for cp, x in crossings(density_md.read_text()).items():
            if cp not in out:
                raise ValueError(f"DENSITY.md names cp{cp}, which the stream does not have")
            out[cp].update(x)
    return out


def crossings(density: str) -> dict[int, dict]:
    """The declared crossings of the ui stream (``acceptance/DENSITY.md``, generated by its
    ``harness.stream_build``). Its last column lists, per checkpoint, each rule it introduces as
    ``rule: degree (partner, ...)``, several separated by ``; ``; the partners are earlier rules a
    value of the checkpoint's own spec depends on together with the new rule. A rule is mapped to the
    checkpoint that introduces it, so each checkpoint gets the earlier checkpoints it crosses."""
    introduced: dict[str, int] = {}
    partners: dict[int, list[tuple[str, list[str]]]] = {}
    for line in density.splitlines():
        cells = [c.strip() for c in line.strip().strip("|").split("|")]
        if len(cells) < 9 or not cells[0].isdigit():
            continue
        cp = int(cells[0])
        for entry in filter(None, (e.strip() for e in cells[8].split(";"))):
            m = re.fullmatch(r"([\w.-]+):\s*(\d+)\s*\(([^)]*)\)", entry)
            if not m:
                raise ValueError(f"cp{cp}: unreadable crossing entry {entry!r}")
            rule, degree = m.group(1), int(m.group(2))
            names = [p.strip() for p in m.group(3).split(",") if p.strip()]
            if len(names) != degree:
                raise ValueError(f"cp{cp}: {rule} declares degree {degree} but names {len(names)}")
            if rule in introduced:
                raise ValueError(f"rule {rule!r} introduced at cp{introduced[rule]} and cp{cp}")
            introduced[rule] = cp
            partners.setdefault(cp, []).append((rule, names))
    out = {}
    for cp, entries in partners.items():
        crossed = set()
        for rule, names in entries:
            for p in names:
                if p not in introduced or introduced[p] >= cp:
                    raise ValueError(f"cp{cp}: {rule} crosses {p!r}, not introduced earlier")
                crossed.add(introduced[p])
        out[cp] = {"rules": [r for r, _ in entries], "crosses": sorted(crossed)}
    return out


def gini(xs: list[float]) -> float:
    xs = sorted(x for x in xs if x > 0)
    n = len(xs)
    if n <= 1:
        return 0.0
    return sum((2 * i - n - 1) * x for i, x in enumerate(xs, start=1)) / (n * sum(xs))


def _hosts(measured: dict):
    return [r for r in measured["records"] if r["kind"] == "host"]


def _type(t: str | None) -> str:
    return (t or "").replace("$", ".")


_GRAPHS: dict[int, "flow.Graph"] = {}


def _graph(index: dict):
    g = _GRAPHS.get(id(index))
    if g is None:
        if len(_GRAPHS) > 64:
            _GRAPHS.clear()
        g = _GRAPHS[id(index)] = flow.Graph(index)
    return g


def choice(r: dict, tm: list[str], tf: list[str], ti: list[str], tc: list[str], places: dict | None) -> dict:
    """Choice (H5, PLAN.md 4.2a): the other places in the tree before the checkpoint that hold what
    this host's code was bound to. At the class: the other classes holding injected dependencies of
    every type the code used; code bound to anything else of its class (its state, a constant, a
    method) has no other class, so none. At the method: the other methods **on the host's control
    flow** (``flow.Graph``) with a parameter or local of every type of the method's values the code
    used (a value of no declared type, ``var`` or an untyped lambda parameter, is left out of the
    match and counted); the count over the whole tree, by type alone, is reported beside it. None
    where the code is not bound at that level, or the host is not found in the tree."""
    out = {"choice_class": None, "choice_class_own": None, "choice_class_places": "",
           "choice_method": None, "choice_method_untyped": None, "choice_method_places": "",
           "choice_method_by_type": None, "choice_flow_methods": None,
           "calls_to_app_names": None, "calls_followed": None}
    index = (places or {}).get(r["unit"])
    if index is None:
        return out
    methods = [m for f in index.get("files", {}).values() for m in f.get("methods", [])]
    classes = [c for f in index.get("files", {}).values() for c in f.get("classes", [])]
    vt, ft = r.get("var_types", {}), r.get("field_types", {})
    if tf or tc:
        own = bool(set(tf) - set(ti) or tc)
        need = {ft[f] for f in ti if f in ft}
        here = _type(r.get("before_type") or r["type"])
        alt = [] if own or not need else sorted(
            c["name"] for c in classes
            if _type(c["name"]) != here and need <= set(c["injected_types"]))
        out.update({"choice_class": len(alt), "choice_class_own": own, "choice_class_places": " ".join(alt)})
    if tm and not r["host_new"]:
        typed = {vt[v] for v in tm if vt.get(v, "var") != "var"}
        untyped = sum(1 for v in tm if vt.get(v, "var") == "var")
        here = (_type(r.get("before_type")), r.get("before_signature"))
        g = _graph(index)
        on = g.flow(*here)
        if typed and on is not None:
            def holds(m):
                return (_type(m["type"]), m["signature"]) != here and typed <= set(m["types"])
            alt = sorted(f"{g.methods[i]['type']}#{g.methods[i]['signature']}" for i in on if holds(g.methods[i]))
            out.update({"choice_method": len(alt), "choice_method_places": " ".join(alt),
                        "choice_method_by_type": sum(1 for m in methods if holds(m)),
                        "choice_flow_methods": len(on),
                        "calls_to_app_names": g.resolution["calls_to_app_names"],
                        "calls_followed": g.resolution["followed"]})
        out["choice_method_untyped"] = untyped
    return out


def host_rows(arm: str, chain: str, measured: dict) -> list[dict]:
    """One row per host and addition. With ``measured["shape"]`` (chain.measure), an existing
    host also carries S1 to S5 of its version at k − 1 (PLAN.md §4.7, ``shape.host_shape``)."""
    from . import flow, shape
    shaped = shape.index(measured.get("shape", []))
    in_class = shape.class_index(measured.get("shape", []))
    # the fields each checkpoint introduces to a class that existed (PLAN.md 4.3b)
    fields_in = {(r["unit"], r["path"], r["type"]): r.get("fields_added_names", [])
                 for r in measured["records"] if r["kind"] == "class"}
    rows = []
    for r in _hosts(measured):
        moved = r["moved_rm"] + r["moved_text"]
        runs = r["runs"]
        tm = sorted({v for x in runs for v in x["binding_method"]})
        tp = sorted({v for x in runs for v in x.get("binding_param", [])})
        ti = sorted({v for x in runs for v in x.get("binding_field_injected", [])})
        tf = sorted({v for x in runs for v in x["binding_field"]})
        tc = sorted({v for x in runs for v in x["binding_class_method"]})
        tu = sorted({v for x in runs for v in x["utility"]})
        un = sorted({v for x in runs for v in x["unresolved"]})
        rows.append({
            "arm": arm, "chain": chain, "cp": int(r["unit"][2:]), "path": r["path"],
            "type": r["type"], "name": r["name"], "signature": r["signature"],
            "before_type": r["before_type"], "before_name": r["before_name"],
            "before_path": r.get("before_path"), "before_signature": r.get("before_signature"),
            "host_new": r["host_new"], "class_new": r["class_new"], "injected": r["injected"],
            "pre_positions": r["pre_positions"], "post_positions": r["post_positions"],
            "added": r["added"], "moved_rm": r["moved_rm"], "moved_text": r["moved_text"],
            "removed": r["removed"], "net_added": r["added"] - moved,
            "replacement": r["added"] > 0 and moved / r["added"] >= REPLACEMENT_SHARE,
            "runs": len(runs), "edits": sum(1 for x in runs if x["replaces"] > 0),
            "binding_method": len(tm), "binding_field": len(tf), "binding_class_method": len(tc),
            "binding_class": len(tf) + len(tc), "binding": len(tm) + len(tf) + len(tc),
            "binding_param": len(tp), "binding_no_param": len(tm) - len(tp) + len(tf) + len(tc),
            "binding_injected": len(ti), "binding_class_no_injected": len(tf) - len(ti) + len(tc),
            "binding_no_injected": len(tm) + len(tf) - len(ti) + len(tc),
            "utility": len(tu), "unresolved": len(un), "unresolved_values": " ".join(un),
            "organisation": r["organisation"],
            "birth_binding": len(r.get("birth_binding", [])),
            "binding_method_values": " ".join(tm),
            "binding_class_values": " ".join(tf + [m + "()" for m in tc]),
            "params": r["params"],
            **standing(runs),
            # introduced (PLAN.md 4.3b): the values the change adds to the method, and the fields its
            # checkpoint adds to the class
            "introduced_method_values": " ".join(sorted(r.get("introduced_method", []))),
            "introduced_class_values": " ".join(sorted(fields_in.get((r["unit"], r["path"], r["type"]), []))),
            # core and periphery at the class (H2): the class's methods there before the change, and
            # those it added, as values "name()"
            "class_methods_pre": " ".join(m + "()" for m in r.get("class_methods_pre", [])),
            "class_methods_added": " ".join(m + "()" for m in r.get("class_methods_added", [])),
            "called_class_methods": " ".join(m + "()" for m in tc),
            **choice(r, tm, tf, ti, tc, measured.get("places")),
        })
        if shaped:
            rows[-1].update(shape.host_shape(rows[-1], shaped, in_class))
    return rows


def run_rows(arm: str, chain: str, measured: dict) -> list[dict]:
    rows = []
    for r in _hosts(measured):
        moved = r["moved_rm"] + r["moved_text"]
        for x in r["runs"]:
            rows.append({
                "arm": arm, "chain": chain, "cp": int(r["unit"][2:]), "type": r["type"],
                "name": r["name"], "signature": r["signature"], "host_new": r["host_new"],
                "injected": r["injected"],
                "replacement": r["added"] > 0 and moved / r["added"] >= REPLACEMENT_SHARE,
                "pre_positions": r["pre_positions"], "positions": x["positions"],
                "replaces": x["replaces"], "edit": x["replaces"] > 0,
                "added_tokens": x["added_tokens"], "inputs": x["inputs"], "outputs": x["outputs"],
                "binding_method": len(x["binding_method"]), "binding_field": len(x["binding_field"]),
                "binding_class_method": len(x["binding_class_method"]),
                "binding_class": len(x["binding_field"]) + len(x["binding_class_method"]),
                "utility": len(x["utility"]),
                "tok_binding_method": x["tok_binding_method"], "tok_binding_class": x["tok_binding_class"],
                "tok_binding": x["tok_binding_method"] + x["tok_binding_class"],
                "unresolved": len(x["unresolved"]), "unresolved_values": " ".join(x["unresolved"]),
                "binding": len(x["binding_method"]) + len(x["binding_field"]) + len(x["binding_class_method"]),
                "binding_param": len(x.get("binding_param", [])),
                "binding_no_param": len(x["binding_method"]) - len(x.get("binding_param", []))
                + len(x["binding_field"]) + len(x["binding_class_method"]),
                "binding_injected": len(x.get("binding_field_injected", [])),
                "binding_class_no_injected": len(x["binding_field"]) - len(x.get("binding_field_injected", []))
                + len(x["binding_class_method"]),
                "binding_no_injected": len(x["binding_method"]) + len(x["binding_field"])
                - len(x.get("binding_field_injected", [])) + len(x["binding_class_method"]),
                "binding_method_values": " ".join(x["binding_method"]),
                "binding_class_values": " ".join(x["binding_field"] + [m + "()" for m in x["binding_class_method"]]),
                "utility_values": " ".join(x["utility"]),
                **bystanders(x),
                # which values: what the run needed and what stood by, in the method and the class
                "need_method_values": " ".join(x.get("need_method", [])),
                "by_method_values": " ".join(sorted(set(x.get("vis_method", [])) - set(x.get("need_method", [])))),
                "need_class_values": " ".join(x.get("need_field_names", [])),
                "by_class_values": " ".join(x.get("by_field_names", [])),
            })
    return rows


def standing(runs: list[dict]) -> dict:
    """For one host and addition (PLAN.md §4.4, H2): the pre-existing values its added code uses
    there and those that stood by, in the method and in the class. A value stands by when it is
    visible to one of the addition's runs in the host and none of them uses it."""
    need_m = {v for x in runs for v in x.get("need_method", [])}
    need_c = {v for x in runs for v in x.get("need_field_names", [])}
    by_m = {v for x in runs for v in x.get("vis_method", [])} - need_m
    by_c = {v for x in runs for v in x.get("by_field_names", [])} - need_c
    return {"need_method_values": " ".join(sorted(need_m)), "by_method_values": " ".join(sorted(by_m)),
            "need_class_values": " ".join(sorted(need_c)), "by_class_values": " ".join(sorted(by_c))}


def bystanders(run: dict) -> dict:
    """§4.3a for one run: the pre-existing values visible where it starts, split into those its
    lines use (``need``) and those they do not (``bystanders``). Method values are parameters,
    injected or not, and locals in scope; class fields are state, injected dependencies and
    constants (a constant is not to be duplicated, so code that needs it comes to it). The
    bystanders count only where the run needs something that was there (``need`` > 0): a run that
    needs nothing was not pulled to its place."""
    vis_m, need_m = len(run.get("vis_method", [])), len(run.get("need_method", []))
    vis_f, need_f = run.get("vis_fields", [0, 0, 0]), run.get("need_fields", [0, 0, 0])
    by_method = vis_m - need_m
    by_state, by_injected, by_constant = (v - n for v, n in zip(vis_f, need_f))
    return {"need": need_m + sum(need_f), "need_constants": need_f[2],
            "by_method": by_method, "by_class": by_state + by_injected + by_constant,
            "bystanders": by_method + by_state + by_injected + by_constant,
            "bystanders_no_injected": by_method + by_state + by_constant,
            "bystanders_no_constants": by_method + by_state + by_injected}


def class_rows(arm: str, chain: str, hosts: list[dict], measured: dict) -> list[dict]:
    """Class level: per addition and class it reaches, the hosts and positions added there and the
    class bindings (distinct pre-existing fields and methods of the class the added code uses)."""
    out: dict[tuple[int, str, str], dict] = {}
    for h in hosts:
        if h["net_added"] <= 0 or h["replacement"]:
            continue
        k = (h["cp"], h["path"], h["type"])
        row = out.setdefault(k, {"arm": arm, "chain": chain, "cp": h["cp"], "path": h["path"],
                                 "type": h["type"], "class_new": h["class_new"], "hosts": 0,
                                 "positions_added": 0, "bindings": set()})
        row["hosts"] += 1
        row["positions_added"] += h["net_added"]
        if h["binding_class_values"]:
            row["bindings"] |= set(h["binding_class_values"].split())
    rows = []
    for row in out.values():
        bindings = sorted(row.pop("bindings"))
        rows.append({**row, "binding_class": len(bindings), "binding_class_values": " ".join(bindings)})
    return sorted(rows, key=lambda r: (r["cp"], r["path"], r["type"]))


def addition_rows(arm: str, chain: str, measured: dict, hosts: list[dict],
                  streamed: dict[int, dict]) -> list[dict]:
    problems = {}
    for r in measured["records"]:
        if r["kind"] == "problem":
            problems[r["unit"]] = problems.get(r["unit"], 0) + 1
    refs = {f["unit"]: len(f["refactorings"]) for f in measured.get("refactorings", [])}
    base = (measured["amount"].get("base") or {}).get("positions", 0)
    # accretion and the heaviest class at k - 1 (PLAN.md 4.3a)
    left, heaviest = {}, {}
    for r in measured["records"]:
        if r["kind"] == "class":
            left[r["unit"]] = left.get(r["unit"], 0) + r["fields_added"]
    for r in measured.get("shape", []):
        heaviest[r["unit"]] = max(heaviest.get(r["unit"], 0), r.get("class_held", 0))
    again = reopened(hosts, measured.get("wiring_changes", {}))
    rows = []
    for c in measured["checkpoints"]:
        cp, unit = c["cp"], f"cp{c['cp']:02d}"
        hs = [h for h in hosts if h["cp"] == cp and h["net_added"] > 0 and not h["replacement"]]
        existing = [h for h in hs if not h["host_new"]]
        added = sum(h["net_added"] for h in hs)
        w = measured["wiring"][unit]
        s = streamed.get(cp, {})
        rows.append({
            "arm": arm, "chain": chain, "cp": cp, "rule": c["rule"], "noop": c["noop"],
            "mutative": s.get("type") == "mutative", "mutates": " ".join(map(str, s.get("mutates", []))),
            "hosts": len(hs), "hosts_existing": len(existing),
            "classes": len({(h["path"], h["type"]) for h in hs}),
            "positions_added": added,
            "positions_in_existing": sum(h["net_added"] for h in existing),
            "share_in_existing": (sum(h["net_added"] for h in existing) / added) if added else None,
            "gini": gini([h["net_added"] for h in hs]),
            "largest_host_pre": max((h["pre_positions"] for h in existing), default=0),
            "binding_method": sum(h["binding_method"] for h in hs),
            "binding_class": sum(h["binding_class"] for h in hs),
            "birth_binding": sum(h["birth_binding"] for h in hs if h["host_new"]),
            "replacements": sum(1 for h in hosts if h["cp"] == cp and h["replacement"]),
            "refactorings": refs.get(unit, 0),
            "amount_positions": measured["amount"][unit]["positions"],
            "amount_methods": measured["amount"][unit]["methods"],
            # the amount added since the chain's base, and the largest method (PLAN.md 4.6, 5)
            "amount_base": base,
            "amount_added": measured["amount"][unit]["positions"] - base,
            "amount_largest": measured["amount"][unit].get("largest"),
            "fields_added": left.get(unit, 0), "heaviest_class": heaviest.get(unit, 0),
            # the parameters and locals the addition introduces to the methods it adds logic to
            "method_values_added": sum(len(h.get("introduced_method_values", "").split()) for h in hs),
            "reopened_classes": again.get(cp, {}).get("reopened_classes", 0),
            "reopened_wiring": again.get(cp, {}).get("reopened_wiring", 0),
            "reopened": sum(again.get(cp, {}).values()),
            "wiring_nodes_added": w["after"]["nodes"] - w["before"]["nodes"],
            "wiring_edges_added": w["after"]["edges"] - w["before"]["edges"],
            "wiring_files": w["after"]["files"], "wiring_edges": w["after"]["edges"],
            "wiring_lines": w["after"]["lines"],
            "wiring_largest_share": (w["after"]["largest_lines"] / w["after"]["lines"])
            if w["after"]["lines"] else None,
            "problems": problems.get(unit, 0),
        })
    return rows


def identities(hosts: list[dict]) -> dict[tuple[int, str, str], str]:
    """A stable identity for each host across renames and moves: a host matched to a differently
    named or typed before version keeps that version's identity."""
    current: dict[tuple[str, str], str] = {}
    out = {}
    for h in sorted(hosts, key=lambda h: h["cp"]):
        key = (h["type"], h["name"])
        if h["before_type"] is not None:
            before = (h["before_type"], h["before_name"])
            ident = current.get(before, f"{before[0]}#{before[1]}")
        else:
            ident = current.get(key, f"{key[0]}#{key[1]}")
        current[key] = ident
        out[(h["cp"], h["type"], h["name"])] = ident
    return out


def outcome_rows(arm: str, chain: str, hosts: list[dict], streamed: dict[int, dict],
                 ct: dict | None = None, followed: dict | None = None) -> list[dict]:
    """§4.4 at method level: for each problem k and each host its code went into, the later
    checkpoints touching the same host, split three ways: those the stream declares to change k's
    rule (``declared``: k in their ``mutates``), those whose new rules it declares to cross k's
    (``crossed``: k in their ``crosses``, ui stream only), and the rest (``intrusion``). A host that survives to the chain's end is followed by CodeTracker (``ct``,
    from ``crosscheck``): its identity and its body-changing checkpoints. A host removed before the
    end is followed by the instrument's own chaining across RefactoringMiner's renames and moves.

    Intrusion is read at three levels (PLAN.md §4.4). The **class** (``intrusion_class``) and the
    **method** (``intrusion_method``) are the placement: every later checkpoint, neither declared
    nor crossing, whose own code in that class, or method, is bound there (``is_bound``). It applies
    only to a problem that was itself bound there (``bound``): a place a problem was not drawn to is
    not one it can be said to have drawn others into. ``*_any`` count any later change, bound or not. The
    problem's **own lines** (``intrusion_lines``, with ``followed`` from ``lines.follow``) are for
    information: a later checkpoint that edits or removes one of them, or inserts between them, is
    changing the problem more than the placement.

    **Drawn in by what stood by** (H2): ``bystanders_class`` and ``bystanders_method`` are the
    pre-existing fields of the class and values of the method that stood by when the problem's code
    was placed in this host (``standing``); ``drawn_class`` and ``drawn_method`` count the later
    intrusions whose bound code there uses one of them.

    **Introduced** (PLAN.md §4.3b, reported): ``introduced_class`` and ``introduced_method`` are
    the fields the problem's checkpoint added to the class and the parameters and locals it added
    to the method; ``drawn_*_introduced`` count the later intrusions whose bound code there uses
    one of them. ``left_*`` is what stood by and what was introduced together, and
    ``drawn_*_left`` the later intrusions bound to either.

    **Core and periphery** (H2 since 19 November 2026, PLAN.md §4.4): for this problem and host the
    **core** is the pre-existing values its code was bound to there (``core_*``: the method's
    values it used, the class's fields it used) and the **periphery** is the rest of what the
    place then held (``periphery_*``: what stood by and what it introduced). ``uses_core_*`` and
    ``uses_periphery_*`` count, over the later intrusions, each value of those it uses, once
    (19 November 2026): at the class, each method the later change's bound code is in is scored on
    its own and the counts summed, and the class's methods are values too (a call to one that was
    there is a core value; those not called, and those added, are periphery)."""
    own = identities(hosts)
    ct_identity = (ct or {}).get("ct_identity", {})
    ct_touched = (ct or {}).get("ct_touched", {})

    def short(t: str) -> str:
        return t.replace("$", ".").split(".")[-1]

    # an own identity any of whose versions CodeTracker recognises becomes that surviving method
    alias: dict[str, str] = {}
    for h in hosts:
        c = ct_identity.get((h["cp"], short(h["type"]), h["name"]))
        if c:
            alias.setdefault(own[(h["cp"], h["type"], h["name"])], c)

    def ident(h: dict) -> str:
        c = ct_identity.get((h["cp"], short(h["type"]), h["name"]))
        o = own[(h["cp"], h["type"], h["name"])]
        return c or alias.get(o) or o

    touched: dict[str, set[int]] = {}
    for h in hosts:
        if h["net_added"] > 0 or h["removed"] > 0:
            touched.setdefault(ident(h), set()).add(h["cp"])
    for c, cps in ct_touched.items():
        touched[c] = set(cps)  # CodeTracker's history is the source for a surviving method
    # the class level: every later checkpoint that changes the class the host is in
    cls = class_identities(hosts)
    class_touched = touched_classes(hosts, cls)
    # drawn in (PLAN.md 4.4): a later checkpoint counts when its own code there is bound, that is,
    # when it reuses data that was already there. Adding a field and its accessor binds nothing.
    class_drawn = touched_classes(hosts, cls, bound=True)
    drawn: dict[str, set[int]] = {}
    for h in hosts:
        if is_bound(h):
            drawn.setdefault(ident(h), set()).add(h["cp"])
    # what each checkpoint's bound code uses, per method and per class (H2: is later code bound to
    # what stood by?)
    uses_m: dict[tuple[str, int], set[str]] = {}
    uses_c: dict[tuple[str, int], set[str]] = {}
    # H2 at the class (19 November 2026): each method a later change's bound code is in is scored
    # on its own, a value counted once per method; the class's methods it calls are values too
    uses_c_hosts: dict[tuple[str, int], list[set[str]]] = {}
    for h in hosts:
        if is_bound(h):
            uses_m.setdefault((ident(h), h["cp"]), set()).update(h.get("need_method_values", "").split())
            uses_c.setdefault((cls[(h["cp"], h["type"])], h["cp"]), set()).update(
                h.get("need_class_values", "").split())
            uses_c_hosts.setdefault((cls[(h["cp"], h["type"])], h["cp"]), []).append(
                set(h.get("need_class_values", "").split()) | set(h.get("called_class_methods", "").split()))
    last = max((h["cp"] for h in hosts), default=0)

    def split(js: list[int], k: int) -> tuple[int, int, int]:
        """(declared, crossed, intrusion) of the later checkpoints js for problem k."""
        declared = [j for j in js if k in streamed.get(j, {}).get("mutates", [])]
        crossed = [j for j in js if j not in declared and k in streamed.get(j, {}).get("crosses", [])]
        return len(declared), len(crossed), len(js) - len(declared) - len(crossed)

    rows = []
    for h in hosts:
        if h["net_added"] <= 0 or h["replacement"]:
            continue
        k, i = h["cp"], ident(h)
        c = cls[(k, h["type"])]
        later = sorted(j for j in drawn.get(i, set()) if j > k)
        later_class = sorted(j for j in class_drawn.get(c, set()) if j > k)
        md, mc, mi = split(later, k)
        cd, cc, ci = split(later_class, k)
        # any later change, bound or not (as first built), reported
        any_m = split(sorted(j for j in touched.get(i, set()) if j > k), k)[2]
        any_c = split(sorted(j for j in class_touched.get(c, set()) if j > k), k)[2]
        # drawn in by what stood by (H2): the later bound arrivals that use a value which was a
        # bystander when this code was placed
        stood_m, stood_c = set(h.get("by_method_values", "").split()), set(h.get("by_class_values", "").split())
        drawn_m = split([j for j in later if uses_m.get((i, j), set()) & stood_m], k)[2]
        drawn_c = split([j for j in later_class if uses_c.get((c, j), set()) & stood_c], k)[2]
        # introduced by this change: the values it added to the method and the fields its checkpoint
        # added to the class; and the later bound arrivals that use one of them
        new_m = set(h.get("introduced_method_values", "").split())
        new_c = set(h.get("introduced_class_values", "").split())
        intro_m = split([j for j in later if uses_m.get((i, j), set()) & new_m], k)[2]
        intro_c = split([j for j in later_class if uses_c.get((c, j), set()) & new_c], k)[2]
        left_m = split([j for j in later if uses_m.get((i, j), set()) & (stood_m | new_m)], k)[2]
        left_c = split([j for j in later_class if uses_c.get((c, j), set()) & (stood_c | new_c)], k)[2]
        # core and periphery (H2): the values this code was bound to, and the rest the place held;
        # each later intrusion's uses of them, value by value
        core_m = set(h.get("need_method_values", "").split())
        core_f = set(h.get("need_class_values", "").split())
        called = set(h.get("called_class_methods", "").split())
        core_c = core_f | called
        methods_there = (set(h.get("class_methods_pre", "").split()) - called) \
            | set(h.get("class_methods_added", "").split())
        peri_m, peri_f = (stood_m | new_m) - core_m, (stood_c | new_c) - core_f
        peri_c = (peri_f | methods_there) - core_c
        intr_m = [j for j in later if k not in streamed.get(j, {}).get("mutates", [])
                  and k not in streamed.get(j, {}).get("crosses", [])]
        intr_c = [j for j in later_class if k not in streamed.get(j, {}).get("mutates", [])
                  and k not in streamed.get(j, {}).get("crosses", [])]
        count = lambda js, uses, key, values: sum(len(uses.get((key, j), set()) & values) for j in js)
        count_c = lambda js, values: sum(len(u & values) for j in js for u in uses_c_hosts.get((c, j), []))
        mine = {"own_lines": None, "own_present": None, "own_lost": None, "own_touches": None,
               "own_declared": None, "own_crossed": None, "intrusion_lines": None}
        if followed is not None:
            f = followed.get((k, h["type"], h.get("signature")),
                             {"placed": 0, "touched": set(), "present": 0, "lost": 0})
            ot = sorted(j for j in f["touched"] if j > k)
            od, oc, oi = split(ot, k)
            mine = {"own_lines": f["placed"], "own_present": f["present"], "own_lost": f["lost"],
                   "own_touches": len(ot), "own_declared": od, "own_crossed": oc,
                   "intrusion_lines": oi}
        rows.append({
            "arm": arm, "chain": chain, "cp": k, "identity": i,
            "identity_source": "codetracker" if i.startswith("ct:") else "instrument",
            "class_identity": c,
            "type": h["type"], "name": h["name"], "signature": h.get("signature"),
            "host_new": h["host_new"], "pre_positions": h["pre_positions"],
            "net_added": h["net_added"], "binding_method": h["binding_method"], "binding_class": h["binding_class"],
            "binding": h["binding"], "bound": is_bound(h), "later_checkpoints": last - k,
            "class_touches": len(later_class), "class_declared": cd, "class_crossed": cc,
            "intrusion_class": ci,
            "later_touches": len(later), "declared": md, "crossed": mc, "intrusion_method": mi,
            "intrusion_class_any": any_c, "intrusion_method_any": any_m,
            "bystanders_class": len(stood_c), "bystanders_method": len(stood_m),
            "drawn_class": drawn_c, "drawn_method": drawn_m,
            "introduced_class": len(new_c), "introduced_method": len(new_m),
            "drawn_class_introduced": intro_c, "drawn_method_introduced": intro_m,
            "left_class": len(stood_c | new_c), "left_method": len(stood_m | new_m),
            "drawn_class_left": left_c, "drawn_method_left": left_m,
            "core_class": len(core_c), "core_method": len(core_m),
            "periphery_class": len(peri_c), "periphery_method": len(peri_m),
            "uses_core_class": count_c(intr_c, core_c),
            "uses_core_method": count(intr_m, uses_m, i, core_m),
            "uses_periphery_class": count_c(intr_c, peri_c),
            # reported: the class's fields only, as until 19 November 2026 (methods not values),
            # each later method still scored on its own
            "core_class_fields": len(core_f), "periphery_class_fields": len(peri_f),
            "uses_core_class_fields": count_c(intr_c, core_f),
            "uses_periphery_class_fields": count_c(intr_c, peri_f),
            "uses_periphery_method": count(intr_m, uses_m, i, peri_m),
            **mine,
            "intrusion_per_100": (100 * ci / (last - k)) if last > k else None,
        })
    return rows


def class_identities(hosts: list[dict]) -> dict[tuple[int, str], str]:
    """(checkpoint, type) -> a stable identity for the class across renames and moves: a host
    matched to a before version of another type keeps that type's identity."""
    current: dict[str, str] = {}
    out = {}
    for h in sorted(hosts, key=lambda h: h["cp"]):
        before = h.get("before_type")
        ident = current.get(before, before) if before else current.get(h["type"], h["type"])
        current[h["type"]] = ident
        out[(h["cp"], h["type"])] = ident
    return out


def is_bound(h: dict) -> bool:
    """Whether the code a checkpoint added to this host is bound there: it reuses data that already
    existed (a parameter or local of the method, a field or method of the class). Only then was it
    drawn to the place, and only then is the place one to watch for what is drawn in later."""
    return h["binding"] >= 1 and h["net_added"] > 0 and not h.get("replacement")


def touched_classes(hosts: list[dict], cls: dict[tuple[int, str], str], bound: bool = False
                    ) -> dict[str, set[int]]:
    """Class identity -> the checkpoints that change any method of it; with ``bound``, only those
    whose code there is bound (``is_bound``)."""
    out: dict[str, set[int]] = {}
    for h in hosts:
        if is_bound(h) if bound else (h["net_added"] > 0 or h["removed"] > 0):
            out.setdefault(cls[(h["cp"], h["type"])], set()).add(h["cp"])
    return out


def reopened(hosts: list[dict], wiring_changes: dict[str, list]) -> dict[int, dict]:
    """Per checkpoint (reported, PLAN.md §4.4): the classes its bound code goes into that an earlier
    checkpoint's bound code had gone into, and the wiring files it changes that an earlier
    checkpoint had created or changed (the function arm's equivalent of the calling method lives
    there; a wiring file has no bindings, so every change counts)."""
    cls = class_identities(hosts)
    by_cp: dict[int, set[str]] = {}
    for c, cps in touched_classes(hosts, cls, bound=True).items():
        for cp in cps:
            by_cp.setdefault(cp, set()).add(c)
    files: dict[int, set[str]] = {}
    for unit, changes in wiring_changes.items():
        files[int(unit[2:])] = {path for status, path in changes}
    created = {int(unit[2:]): {path for status, path in changes if status == "A"}
               for unit, changes in wiring_changes.items()}
    out = {}
    seen_c: set[str] = set()
    seen_f: set[str] = set()
    for cp in sorted(set(by_cp) | set(files)):
        c = by_cp.get(cp, set())
        f = files.get(cp, set())
        out[cp] = {"reopened_classes": len(c & seen_c),
                   "reopened_wiring": len((f - created.get(cp, set())) & seen_f)}
        seen_c |= c
        seen_f |= f
    return out
