def standing(runs: list[dict]) -> dict:
    """For one host and addition (PLAN.md §4.4, H2): the pre-existing values its added code uses
    there and those that stood by, in the method and in the class. A value stands by when it is
    visible to one of the addition's runs in the host and none of them uses it."""
    need_m = {v for x in runs for v in x.get("need_method", [])}
    need_c = {v for x in runs for v in x.get("need_field_names", [])}
    by_m = {v for x in runs for v in x.get("vis_method", [])} - need_m
    by_c = {v for x in runs for v in x.get("by_field_names", [])} - need_c
    return {"need_method_values": " ".join(sorted(need_m)), "by_method_values": " ".join(sorted(by_m)),
            "need_class_values": " ".join(sorted(need_c)), "by_class_values": " ".join(sorted(by_c))}


def bystanders(run: dict) -> dict:
    """§4.3a for one run: the pre-existing values visible where it starts, split into those its
    lines use (``need``) and those they do not (``bystanders``). Method values are parameters,
    injected or not, and locals in scope; class fields are state, injected dependencies and
    constants (a constant is not to be duplicated, so code that needs it comes to it). The
    bystanders count only where the run needs something that was there (``need`` > 0): a run that
    needs nothing was not pulled to its place."""
    vis_m, need_m = len(run.get("vis_method", [])), len(run.get("need_method", []))
    vis_f, need_f = run.get("vis_fields", [0, 0, 0]), run.get("need_fields", [0, 0, 0])
    by_method = vis_m - need_m
    by_state, by_injected, by_constant = (v - n for v, n in zip(vis_f, need_f))
    return {"need": need_m + sum(need_f), "need_constants": need_f[2],
            "by_method": by_method, "by_class": by_state + by_injected + by_constant,
            "bystanders": by_method + by_state + by_injected + by_constant,
            "bystanders_no_injected": by_method + by_state + by_constant,
            "bystanders_no_constants": by_method + by_state + by_injected}


def class_rows(arm: str, chain: str, hosts: list[dict], measured: dict) -> list[dict]:
    """Class level: per addition and class it reaches, the hosts and positions added there and the
    class bindings (distinct pre-existing fields and methods of the class the added code uses)."""
    out: dict[tuple[int, str, str], dict] = {}
    for h in hosts:
        if h["net_added"] <= 0 or h["replacement"]:
            continue
        k = (h["cp"], h["path"], h["type"])
        row = out.setdefault(k, {"arm": arm, "chain": chain, "cp": h["cp"], "path": h["path"],
                                 "type": h["type"], "class_new": h["class_new"], "hosts": 0,
                                 "positions_added": 0, "bindings": set()})
        row["hosts"] += 1
        row["positions_added"] += h["net_added"]
        if h["binding_class_values"]:
            row["bindings"] |= set(h["binding_class_values"].split())
    rows = []
    for row in out.values():
        bindings = sorted(row.pop("bindings"))
        rows.append({**row, "binding_class": len(bindings), "binding_class_values": " ".join(bindings)})
    return sorted(rows, key=lambda r: (r["cp"], r["path"], r["type"]))


