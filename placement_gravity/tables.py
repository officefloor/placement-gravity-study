def stream(checkpoints_yaml: Path, density_md: Path | None = None) -> dict[int, dict]:
    """cp number (1-based, the stream's order) -> {id, type, mutates, rules, crosses}. ``mutates``
    lists the checkpoints whose rules this one changes (both streams). With the ui stream's
    ``acceptance/DENSITY.md``, ``rules`` are the rules this checkpoint introduces and ``crosses`` the
    checkpoints whose rules they interact with (``crossings``); otherwise both are empty."""
    doc = yaml.safe_load(checkpoints_yaml.read_text())
    out = {i: {"id": c["id"], "type": c.get("type", "additive"),
               "mutates": list(c.get("mutates") or []), "rules": [], "crosses": []}
           for i, c in enumerate(doc["checkpoints"], start=1)}
    if density_md is not None:
        for cp, x in crossings(density_md.read_text()).items():
            if cp not in out:
                raise ValueError(f"DENSITY.md names cp{cp}, which the stream does not have")
            out[cp].update(x)
    return out


def crossings(density: str) -> dict[int, dict]:
    """The declared crossings of the ui stream (``acceptance/DENSITY.md``, generated by its
    ``harness.stream_build``). Its last column lists, per checkpoint, each rule it introduces as
    ``rule: degree (partner, ...)``, several separated by ``; ``; the partners are earlier rules a
    value of the checkpoint's own spec depends on together with the new rule. A rule is mapped to the
    checkpoint that introduces it, so each checkpoint gets the earlier checkpoints it crosses."""
    introduced: dict[str, int] = {}
    partners: dict[int, list[tuple[str, list[str]]]] = {}
    for line in density.splitlines():
        cells = [c.strip() for c in line.strip().strip("|").split("|")]
        if len(cells) < 9 or not cells[0].isdigit():
            continue
        cp = int(cells[0])
        for entry in filter(None, (e.strip() for e in cells[8].split(";"))):
            m = re.fullmatch(r"([\w.-]+):\s*(\d+)\s*\(([^)]*)\)", entry)
            if not m:
                raise ValueError(f"cp{cp}: unreadable crossing entry {entry!r}")
            rule, degree = m.group(1), int(m.group(2))
            names = [p.strip() for p in m.group(3).split(",") if p.strip()]
            if len(names) != degree:
                raise ValueError(f"cp{cp}: {rule} declares degree {degree} but names {len(names)}")
            if rule in introduced:
                raise ValueError(f"rule {rule!r} introduced at cp{introduced[rule]} and cp{cp}")
            introduced[rule] = cp
            partners.setdefault(cp, []).append((rule, names))
    out = {}
    for cp, entries in partners.items():
        crossed = set()
        for rule, names in entries:
            for p in names:
                if p not in introduced or introduced[p] >= cp:
                    raise ValueError(f"cp{cp}: {rule} crosses {p!r}, not introduced earlier")
                crossed.add(introduced[p])
        out[cp] = {"rules": [r for r, _ in entries], "crosses": sorted(crossed)}
    return out


def gini(xs: list[float]) -> float:
    xs = sorted(x for x in xs if x > 0)
    n = len(xs)
    if n <= 1:
        return 0.0
    return sum((2 * i - n - 1) * x for i, x in enumerate(xs, start=1)) / (n * sum(xs))


def _hosts(measured: dict):
    return [r for r in measured["records"] if r["kind"] == "host"]


def _type(t: str | None) -> str:
    return (t or "").replace("$", ".")


_GRAPHS: dict[int, "flow.Graph"] = {}


def _graph(index: dict):
    g = _GRAPHS.get(id(index))
    if g is None:
        if len(_GRAPHS) > 64:
            _GRAPHS.clear()
        g = _GRAPHS[id(index)] = flow.Graph(index)
    return g


def choice(r: dict, tm: list[str], tf: list[str], ti: list[str], tc: list[str], places: dict | None) -> dict:
    """Choice (H1, PLAN.md 4.2a): the other places in the tree before the checkpoint that hold what
    this host's code was bound to. At the class: the other classes holding injected dependencies of
    every type the code used; code bound to anything else of its class (its state, a constant, a
    method) has no other class, so none. At the method: the other methods **on the host's control
    flow** (``flow.Graph``) with a parameter or local of every type of the method's values the code
    used (a value of no declared type, ``var`` or an untyped lambda parameter, is left out of the
    match and counted); the count over the whole tree, by type alone, is reported beside it. None
    where the code is not bound at that level, or the host is not found in the tree."""
    out = {"choice_class": None, "choice_class_own": None, "choice_class_places": "",
           "choice_method": None, "choice_method_untyped": None, "choice_method_places": "",
           "choice_method_by_type": None, "choice_flow_methods": None,
           "calls_to_app_names": None, "calls_followed": None}
    index = (places or {}).get(r["unit"])
    if index is None:
        return out
    methods = [m for f in index.get("files", {}).values() for m in f.get("methods", [])]
    classes = [c for f in index.get("files", {}).values() for c in f.get("classes", [])]
    vt, ft = r.get("var_types", {}), r.get("field_types", {})
    if tf or tc:
        own = bool(set(tf) - set(ti) or tc)
        need = {ft[f] for f in ti if f in ft}
        here = _type(r.get("before_type") or r["type"])
        alt = [] if own or not need else sorted(
            c["name"] for c in classes
            if _type(c["name"]) != here and need <= set(c["injected_types"]))
        out.update({"choice_class": len(alt), "choice_class_own": own, "choice_class_places": " ".join(alt)})
    if tm and not r["host_new"]:
        typed = {vt[v] for v in tm if vt.get(v, "var") != "var"}
        untyped = sum(1 for v in tm if vt.get(v, "var") == "var")
        here = (_type(r.get("before_type")), r.get("before_signature"))
        g = _graph(index)
        on = g.flow(*here)
        if typed and on is not None:
            def holds(m):
                return (_type(m["type"]), m["signature"]) != here and typed <= set(m["types"])
            alt = sorted(f"{g.methods[i]['type']}#{g.methods[i]['signature']}" for i in on if holds(g.methods[i]))
            out.update({"choice_method": len(alt), "choice_method_places": " ".join(alt),
                        "choice_method_by_type": sum(1 for m in methods if holds(m)),
                        "choice_flow_methods": len(on),
                        "calls_to_app_names": g.resolution["calls_to_app_names"],
                        "calls_followed": g.resolution["followed"]})
        out["choice_method_untyped"] = untyped
    return out


def member_access(r: dict, places: dict | None) -> dict[str, str] | None:
    """The access of each member of a host's class in the tree before the unit: fields by name,
    methods as "name()" (of a name's overloads, the strictest). None where the class is not in that
    tree."""
    index = (places or {}).get(r["unit"])
    if index is None:
        return None
    here = flow.simple(r.get("before_type") or r["type"])
    fields, methods = None, {}
    for f in index.get("files", {}).values():
        for c in f.get("classes", []):
            if flow.simple(c["name"]) == here and "fields" in c:
                fields = c["fields"]
        for m in f.get("methods", []):
            if flow.simple(m["type"]) == here:
                n = f"{m.get('name') or m['signature'].split('(')[0]}()"
                a = m.get("access", "public")
                if n not in methods or ACCESS.get(a, 3) < ACCESS.get(methods[n], 3):
                    methods[n] = a
    if fields is None:
        return None
    return {**dict(fields), **methods}


def bound_access(r: dict, tf: list[str], tc: list[str], places: dict | None) -> str | None:
    """The strictest access among the class members the code was bound to (private, package,
    protected, public): private is the encapsulation that forces; package and protected are looser,
    reported descriptively (decided by the author on 22 November 2026). None where the code was not
    bound at the class, or the class is not in the tree before."""
    acc = member_access(r, places) if (tf or tc) else None
    if acc is None:
        return None
    seen = [acc[v] for v in list(tf) + [f"{m}()" for m in tc] if v in acc]
    return min(seen, key=lambda a: ACCESS.get(a, 3)) if seen else None


def private_members(r: dict, places: dict | None) -> set[str] | None:
    """The members of a host's class that no other class can reach, in the tree before the unit: its
    private fields (a private constant among them) by name, and its private methods as "name()" (a
    name with any private overload counts). None where the class is not in that tree."""
    index = (places or {}).get(r["unit"])
    if index is None:
        return None
    here = flow.simple(r.get("before_type") or r["type"])
    fields, methods = None, {}
    for f in index.get("files", {}).values():
        for c in f.get("classes", []):
            if flow.simple(c["name"]) == here and "fields" in c:
                fields = c["fields"]
        for m in f.get("methods", []):
            if flow.simple(m["type"]) == here:
                methods.setdefault(m.get("name") or m["signature"].split("(")[0], set()).add(m.get("access", "public"))
    if fields is None:
        return None
    return ({v for v, a in fields.items() if a == "private"}
            | {f"{n}()" for n, accs in methods.items() if "private" in accs})


def encapsulated(r: dict, tf: list[str], tc: list[str], places: dict | None) -> bool | None:
    """Forced by encapsulation (PLAN.md §2, decided by the author on 21 November 2026): the code was
    bound at the class to a member no other class can reach, a private field (a constant among
    them) or a private method. False where it was bound at the class only to members other classes
    can reach (a public constant is open for others to use: the author's "good code"); None where it
    was not bound at the class, or the class is not in the tree before the unit."""
    if not (tf or tc):
        return None
    index = (places or {}).get(r["unit"])
    if index is None:
        return None
    here = flow.simple(r.get("before_type") or r["type"])
    fields, methods = None, {}
    for f in index.get("files", {}).values():
        for c in f.get("classes", []):
            if flow.simple(c["name"]) == here and "fields" in c:
                fields = c["fields"]
        for m in f.get("methods", []):
            if flow.simple(m["type"]) == here:
                methods.setdefault(m.get("name") or m["signature"].split("(")[0], set()).add(m.get("access", "public"))
    if fields is None:
        return None
    return (any(fields.get(v) == "private" for v in tf)
            or any("private" in methods.get(v, set()) for v in tc))


def lever(r: dict, tf: list[str], ti: list[str], tc: list[str], places: dict | None) -> str | None:
    """Within forced by encapsulation, whether the lever of injection was there (decided by the
    author on 22 November 2026). ``injected``: every private member the code was bound to is a field
    holding an injected dependency, which another class could declare too, so the core could be
    duplicated elsewhere; the choice exists as a construct and was not exercised (whether another
    class already holds those dependencies is H1's ``choice_class``). ``own``: it was bound to a
    private field of the class's own state, a private constant or a private method, which nothing
    outside can reach. None where the placement was not forced by encapsulation."""
    private = private_members(r, places) if (tf or tc) else None
    if private is None:
        return None
    used = {v for v in tf if v in private} | {f"{m}()" for m in tc if f"{m}()" in private}
    if not used:
        return None
    return "injected" if used <= set(ti) else "own"


def forced(h: dict) -> bool | None:
    """A host's placement forced by encapsulation (``forced_enc``): True, False, or None where its
    code was not bound at the class."""
    v = h.get("forced_enc")
    return None if v in (None, "") else str(v) == "True"


def changed(h: dict) -> bool:
    """A host a unit placed or edited code in (H7, PLAN.md 4.2b): it added positions, and is not a
    re-placement of code moved there."""
    return float(h.get("added") or 0) > 0 and str(h.get("replacement")) != "True"


def _trees(measured: dict) -> tuple[dict, dict]:
    """The tree before each unit, by unit number, and the unit whose tree follows each one (the
    tree after a unit is the tree before the next; the last unit has none)."""
    places = measured.get("places") or {}
    by = {int(k[2:]): v for k, v in places.items()}
    order = sorted(by)
    return by, dict(zip(order, order[1:]))


def pair_rows(arm: str, chain: str, hosts: list[dict], measured: dict) -> list[dict]:
    """Change spread (H7, PLAN.md 4.2b): per unit, every pair of classes it placed or edited code
    in, with the calls between them in the tree before the unit and in the tree after it (before
    the next unit; on a history, with any commits between that are not units), followed by their
    receiver's type (``flow.Graph.class_calls``), each way. A class not in the tree before (new in
    the unit) has none there; ``in_tree`` says whether both were there, ``new`` how many were new."""
    from itertools import combinations
    trees, after = _trees(measured)
    by_cp: dict[int, dict[str, bool]] = {}
    for h in hosts:
        if changed(h):
            c = _type(h.get("before_type") or h["type"])
            cs = by_cp.setdefault(int(h["cp"]), {})
            cs[c] = cs.get(c, True) and str(h.get("class_new")) == "True"

    def calls(index):
        return _graph(index).class_calls() if index is not None else None

    out = []
    for cp, cs in sorted(by_cp.items()):
        index = trees.get(cp)
        g = _graph(index) if index is not None else None
        before = calls(index) or {}
        nxt = calls(trees.get(after.get(cp))) if after.get(cp) is not None else None
        there = {flow.simple(m["type"]) for m in g.methods} if g else set()
        for a, b in combinations(sorted(cs), 2):
            sa, sb = flow.simple(a), flow.simple(b)
            out.append({"arm": arm, "chain": chain, "cp": cp, "class_a": a, "class_b": b,
                        "calls_ab": before.get((sa, sb), 0), "calls_ba": before.get((sb, sa), 0),
                        "calls_ab_after": None if nxt is None else nxt.get((sa, sb), 0),
                        "calls_ba_after": None if nxt is None else nxt.get((sb, sa), 0),
                        "in_tree": sa in there and sb in there, "new": int(cs[a]) + int(cs[b])})
    return out


def coupling_rows(arm: str, chain: str, measured: dict) -> list[dict]:
    """The coupling of the whole tree (H7's accounting, PLAN.md 4.2b): per unit, the calls followed
    from one class to another in the tree before it and in the tree after it, so that what a unit
    added between all classes, changed together or not, can be counted."""
    trees, after = _trees(measured)

    def total(index):
        return sum(_graph(index).class_calls().values())

    return [{"arm": arm, "chain": chain, "cp": cp, "cross_class_calls": total(trees[cp]),
             "cross_class_calls_after": total(trees[after[cp]]) if cp in after else None}
            for cp in sorted(trees)]


#: Access, from closed to open (H5): a member whose rank rises was widened.
ACCESS = {"private": 0, "package": 1, "protected": 2, "public": 3}


def encapsulation_rows(arm: str, chain: str, hosts: list[dict], measured: dict) -> list[dict]:
    """Forced coupling (H5, PLAN.md 4.2c): per unit and class that existed before it that the unit
    placed or edited code in, the calls across that class's boundary the unit added (in the tree
    after it, which is the tree before the next unit, and not before), outward (from its methods to
    another class's) and inward (from another class's methods to its own), each by the member it
    reaches, a method or a field: one that was already open to it (*existing*), one the unit added
    open to other classes (*exposed*, not private), or one the unit made more open (*widened*). With
    whether a placement in the class was forced by encapsulation (``forced``; bound to a member no
    other class can reach) or bound only to reachable members (``chosen``), whether one was forced by
    binding with no alternative (``forced_bind``, H1's class level), and how many of the class's own
    members the unit exposed or widened, called or not."""
    trees, after = _trees(measured)
    by_cp = _forced_classes(hosts)
    out = []
    for cp, classes in sorted(by_cp.items()):
        if cp not in trees or cp not in after:
            continue
        g0, g1 = _graph(trees[cp]), _graph(trees[after[cp]])
        e0, e1 = g0.cross_edges(), g1.cross_edges()
        a0, a1 = g0.access(), g1.access()
        new, lost = e1 - e0, e0 - e1

        def kind(callee):
            if callee not in a0:
                return "exposed"
            return "widened" if ACCESS.get(a1.get(callee), 3) > ACCESS.get(a0[callee], 3) else "existing"

        for c, d in sorted(classes.items()):
            sc = flow.simple(c)
            row = {"arm": arm, "chain": chain, "cp": cp, "class": c, "forced": d["forced"], "chosen": d["chosen"],
                   "forced_bind": d["forced_bind"]}
            for side, mine in (("out", lambda e: e[0][0] == sc), ("in", lambda e: e[1][0] == sc)):
                edges = [e for e in new if mine(e)]
                row[f"new_{side}"] = len(edges)
                row[f"lost_{side}"] = sum(1 for e in lost if mine(e))
                for k in ("existing", "exposed", "widened"):
                    row[f"{side}_{k}"] = sum(1 for e in edges if kind(e[1]) == k)
            row["members_opened"] = sum(
                1 for (t, sig), acc in a1.items() if t == sc and acc != "private"
                and ((t, sig) not in a0 or ACCESS.get(acc, 3) > ACCESS.get(a0[(t, sig)], 3)))
            out.append(row)
    return out


def member_rows(arm: str, chain: str, measured: dict) -> list[dict]:
    """Encapsulation and the reader (PLAN.md 4.2f): per unit with a tree after it, the fields and
    methods it introduced into the application's classes (a member of the tree after that was not
    in the tree before, by class and signature, a field as "#name"; a renamed member counts as
    introduced) and how many of them are private, fields apart; and the size of the system before
    it: its files, classes, methods and tokens (``chain.java_tokens``), so that the unit can be read
    against a context window."""
    trees, after = _trees(measured)
    out = []
    for cp in sorted(trees):
        index = trees[cp]
        files = index.get("files", {})
        row = {"arm": arm, "chain": chain, "cp": cp, "system_files": len(files),
               "system_classes": sum(len(f.get("classes", [])) for f in files.values()),
               "system_methods": sum(len(f.get("methods", [])) for f in files.values()),
               "system_tokens": sum(int(f.get("tokens") or 0) for f in files.values())}
        if cp in after:
            a0, a1 = _graph(index).access(), _graph(trees[after[cp]]).access()
            new = {k: v for k, v in a1.items() if k not in a0}
            row.update({"introduced": len(new),
                        "introduced_private": sum(1 for v in new.values() if v == "private"),
                        "introduced_fields": sum(1 for k in new if k[1].startswith("#")),
                        "introduced_private_fields": sum(1 for k, v in new.items()
                                                         if k[1].startswith("#") and v == "private")})
        else:
            row.update({"introduced": None, "introduced_private": None, "introduced_fields": None,
                        "introduced_private_fields": None})
        out.append(row)
    return out


def _forced_classes(hosts: list[dict]) -> dict[int, dict[str, dict]]:
    """Per unit, the classes that existed that it placed or edited code in, each with whether a
    placement there was forced at the class or had a choice (H1's class level)."""
    by_cp: dict[int, dict[str, dict]] = {}
    for h in hosts:
        if not changed(h) or str(h.get("class_new")) == "True":
            continue
        c = _type(h.get("before_type") or h["type"])
        d = by_cp.setdefault(int(h["cp"]), {}).setdefault(c, {"forced": False, "chosen": False, "forced_bind": False})
        f = forced(h)
        if f is not None:
            d["forced" if f else "chosen"] = True
        n = h.get("choice_class")
        if n not in (None, "") and int(float(n)) == 0:
            d["forced_bind"] = True
    return by_cp


def boundary_rows(arm: str, chain: str, hosts: list[dict], measured: dict) -> list[dict]:
    """Surface against volume (PLAN.md 4.2e): per unit and class that existed that it changed, the
    class's volume (its methods; its positions where the shape of the tree was read) and its surface
    (the calls followed out of it and into it, and the classes on each side) in the tree before the
    unit and in the tree after it, with whether the class was forced in the unit. Then, per chain,
    every class of the last tree (``cross_section``), for the relation across classes."""
    trees, after = _trees(measured)
    sizes: dict[tuple[str, str], int] = {}
    for r in measured.get("shape") or []:
        k = (str(r["unit"]), flow.simple(r["type"]))
        sizes[k] = sizes.get(k, 0) + int(r.get("positions") or 0)

    def state(cp, g):
        calls = g.class_calls()
        out = {}
        for (a, b), n in calls.items():
            o = out.setdefault(a, [0, 0, set(), set()])
            o[0] += n
            o[2].add(b)
            i = out.setdefault(b, [0, 0, set(), set()])
            i[1] += n
            i[3].add(a)
        methods: dict[str, int] = {}
        for m in g.methods:
            methods[flow.simple(m["type"])] = methods.get(flow.simple(m["type"]), 0) + 1
        return methods, out

    rows = []
    for cp, classes in sorted(_forced_classes(hosts).items()):
        if cp not in trees or cp not in after:
            continue
        m0, s0 = state(cp, _graph(trees[cp]))
        m1, s1 = state(after[cp], _graph(trees[after[cp]]))
        for c, d in sorted(classes.items()):
            sc = flow.simple(c)
            row = {"arm": arm, "chain": chain, "cp": cp, "class": c, "forced": d["forced"], "chosen": d["chosen"],
                   "cross_section": False}
            for tag, m, s, unit in (("before", m0, s0, cp), ("after", m1, s1, after[cp])):
                o = s.get(sc, [0, 0, set(), set()])
                row.update({f"methods_{tag}": m.get(sc, 0),
                            f"positions_{tag}": sizes.get((f"cp{unit:02d}", sc)),
                            f"out_{tag}": o[0], f"in_{tag}": o[1],
                            f"out_classes_{tag}": len(o[2]), f"in_classes_{tag}": len(o[3])})
            rows.append(row)
    if trees:
        last = max(trees)
        m, s = state(last, _graph(trees[last]))
        for sc in sorted(m):
            o = s.get(sc, [0, 0, set(), set()])
            rows.append({"arm": arm, "chain": chain, "cp": last, "class": sc, "forced": None, "chosen": None,
                         "cross_section": True, "methods_before": m[sc],
                         "positions_before": sizes.get((f"cp{last:02d}", sc)),
                         "out_before": o[0], "in_before": o[1],
                         "out_classes_before": len(o[2]), "in_classes_before": len(o[3])})
    return rows


def edge_rows(arm: str, chain: str, hosts: list[dict], measured: dict) -> list[dict]:
    """The calls across a class's boundary each unit added (H5's calls, PLAN.md 4.2c), one row each,
    for the ripple reading (4.2e): the caller's class and method, the callee's class and method, the
    kind of member reached (existing, exposed, widened), and whether the caller's or the callee's
    class was forced in the unit."""
    trees, after = _trees(measured)
    out = []
    for cp, classes in sorted(_forced_classes(hosts).items()):
        if cp not in trees or cp not in after:
            continue
        g0, g1 = _graph(trees[cp]), _graph(trees[after[cp]])
        a0, a1 = g0.access(), g1.access()
        mine = {flow.simple(c): d for c, d in classes.items()}
        for caller, callee in sorted(g1.cross_edges() - g0.cross_edges()):
            if caller[0] not in mine and callee[0] not in mine:
                continue
            kind = ("exposed" if callee not in a0 else
                    "widened" if ACCESS.get(a1.get(callee), 3) > ACCESS.get(a0[callee], 3) else "existing")
            out.append({"arm": arm, "chain": chain, "cp": cp, "caller_class": caller[0],
                        "caller_signature": caller[1], "callee_class": callee[0],
                        "callee_signature": callee[1], "kind": kind,
                        "caller_forced": mine.get(caller[0], {}).get("forced", False),
                        "callee_forced": mine.get(callee[0], {}).get("forced", False)})
    return out


def link_rows(arm: str, chain: str, measured: dict) -> list[dict]:
    """Surface against volume (H5, PLAN.md 4.2c, restated 24 November 2026): per checkpoint, the
    links between blocks of logic it added and lost, by kind: **call** (a method to a method it
    calls), **state** (a method to a field holding state that it uses; not an injected dependency,
    not a constant) and **flow** (an edge of the OfficeFloor wiring, one function to the next). A
    link is counted once, however heavy. Java links compare the tree before the checkpoint with the
    tree before the next; the wiring compares the checkpoint's parent with its commit. The last
    checkpoint has no tree after it and no row. With the tree's totals before it (``*_links``) and its
    methods."""
    trees, after = _trees(measured)
    rows = []
    for cp in sorted(trees):
        if cp not in after:
            continue
        g0, g1 = _graph(trees[cp]), _graph(trees[after[cp]])
        l0, l1 = g0.links(), g1.links()
        w = (measured.get("wiring") or {}).get(f"cp{cp:02d}") or {}
        f0 = set((w.get("before") or {}).get("links") or [])
        f1 = set((w.get("after") or {}).get("links") or [])
        row = {"arm": arm, "chain": chain, "cp": cp}
        for kind, a, b in (("call", l0["call"], l1["call"]), ("state", l0["state"], l1["state"]),
                           ("flow", f0, f1)):
            row[f"{kind}_links_added"] = len(b - a)
            row[f"{kind}_links_lost"] = len(a - b)
            row[f"{kind}_links"] = len(a)
        row["links_added"] = sum(row[f"{k}_links_added"] for k in ("call", "state", "flow"))
        row["links_lost"] = sum(row[f"{k}_links_lost"] for k in ("call", "state", "flow"))
        row["methods"] = len(g0.methods)
        rows.append(row)
    return rows


#: RefactoringMiner's kinds that split a class or move members between classes (the redesign
#: reading's check, PLAN.md 4.2d).
SPLITS = {"Extract Class", "Extract Subclass"}
MOVES = {"Move Method", "Move And Rename Method", "Move Attribute", "Move And Rename Attribute",
         "Move And Inline Method"}
_EXTRACT = re.compile(r"^Extract (?:Class|Subclass) (\S+) from class (\S+)")
_FROM_TO = re.compile(r"from class (\S+) to class (\S+)")


def refactoring_rows(arm: str, chain: str, measured: dict) -> list[dict]:
    """The refactorings RefactoringMiner found that split a class (Extract Class, Extract Subclass)
    or move a member between two classes (PLAN.md 4.2d), one row each: the unit, the kind, and the
    classes from and to (as RefactoringMiner names them, qualified)."""
    out = []
    for found in measured.get("refactorings") or []:
        cp = int(str(found["unit"])[2:])
        for r in found.get("refactorings", []):
            kind, desc = r.get("type", ""), r.get("description", "")
            if kind in SPLITS and (m := _EXTRACT.match(desc)):
                to, frm = m.group(1), m.group(2)
            elif kind in MOVES and (m := _FROM_TO.search(desc)):
                frm, to = m.group(1), m.group(2)
            else:
                continue
            out.append({"arm": arm, "chain": chain, "cp": cp, "kind": kind,
                        "from_class": frm, "to_class": to})
    return out


